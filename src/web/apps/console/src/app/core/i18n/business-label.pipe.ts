@Pipe({ name: 'businessLabel', standalone: true, pure: false })
export class BusinessLabelPipe implements PipeTransform {
  private readonly i18n = inject(I18nService);

  transform(value: unknown, domain: string, position = 0): string {
    const language = this.i18n.currentLang();
    this.i18n.isLoaded();
    const values = Object.hasOwn(LABELS, domain) ? LABELS[domain] : undefined;
    const normalized =
      typeof value === 'string' || typeof value === 'number' ? String(value).toLowerCase() : '';
    const key = values && Object.hasOwn(values, normalized) ? values[normalized] : undefined;
    if (key) {
      const label = this.i18n.translate(key);
      if (label && label !== key) return label;
    }
    const fallbackKey =
      domain === 'auditField' ? 'BUSINESS_LABELS.OTHER_FIELD' : 'BUSINESS_LABELS.UNAVAILABLE';
    const fallback = this.i18n.translate(fallbackKey, { index: position + 1 });
    if (fallback && fallback !== fallbackKey) return fallback;
    const labels = fallbackLabels[language === 'zh-CN' ? 'zh-CN' : 'en-NZ'];
    return domain === 'auditField'
      ? labels.otherField.replace('{index}', String(position + 1))
      : labels.unavailable;
  }
}
